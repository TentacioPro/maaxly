// Generate src/theme/presets.js from tweakcn-components/utils/theme-presets.ts
// Converts tweakcn defaultPresets (TS) to our variant-aware CSS variable maps.

const fs = require('fs')
const path = require('path')
const vm = require('vm')

const ROOT = path.resolve(__dirname, '../../')
const srcTs = path.join(ROOT, 'tweakcn-components', 'utils', 'theme-presets.ts')
const outJs = path.join(ROOT, 'src', 'theme', 'presets.js')

function readDefaultPresetsTS() {
  return fs.readFileSync(srcTs, 'utf8')
}

function evaluatePresets(code) {
  let js = code.replace(/^import[\s\S]*?;\s*/g, '')
  js = js.replace(/export\s+const\s+defaultPresets\s*:[^=]*=/, 'module.exports =')
  const context = { module: { exports: {} }, exports: {} }
  vm.runInNewContext(js, context, { filename: 'theme-presets.ts' })
  return context.module.exports
}

const SUPPORTED = new Set([
  'background','foreground','card','card-foreground','popover','popover-foreground',
  'primary','primary-foreground','secondary','secondary-foreground',
  'muted','muted-foreground','accent','accent-foreground','destructive','destructive-foreground',
  'border','input','ring','radius','font-sans','font-serif','font-mono'
])

function toCssVarMap(style) {
  const out = {}
  for (const [k, v] of Object.entries(style || {})) {
    if (!SUPPORTED.has(k)) continue
    out[`--${k}`] = v
  }
  return out
}

function buildThemePresets(defaultPresets) {
  const list = []
  for (const [id, preset] of Object.entries(defaultPresets || {})) {
    const light = toCssVarMap(preset.styles?.light || {})
    const dark = toCssVarMap(preset.styles?.dark || {})
    const preview = preset.styles?.light?.primary || preset.styles?.dark?.primary || preset.styles?.light?.accent || '#888888'
    list.push({ id, name: preset.label || id, preview, tokens: { light, dark } })
  }
  return list
}

function writeOutput(themePresets) {
  const banner = `// AUTO-GENERATED by server/scripts/generate-theme-presets.cjs\n// Source: tweakcn-components/utils/theme-presets.ts\n// Do not edit by hand.\n\n`
  const body = 'export const themePresets = ' + JSON.stringify(themePresets, null, 2) + '\n'
  fs.mkdirSync(path.dirname(outJs), { recursive: true })
  fs.writeFileSync(outJs, banner + body, 'utf8')
}

function main() {
  const code = readDefaultPresetsTS()
  const obj = evaluatePresets(code)
  const presets = buildThemePresets(obj)
  writeOutput(presets)
  console.log(`Generated ${presets.length} presets to ${path.relative(ROOT, outJs)}`)
}

if (require.main === module) {
  try { main() } catch (e) { console.error(e); process.exit(1) }
}
